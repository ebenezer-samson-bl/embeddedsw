#define debug(...) do { XFsbl_Printf(DEBUG_DETAILED, __VA_ARGS__); } while(0)
//#define debug(...) do { XFsbl_Printf(DEBUG_PRINT_ALWAYS, __VA_ARGS__); } while(0)
#define error(...) do { XFsbl_Printf(DEBUG_PRINT_ALWAYS, __VA_ARGS__); } while(0)

int clk_gen_cnf(XIicPs *IicPsInstance) {
    int Status, cStatus;

    u32 i = 0;
    u32 nbytes = sizeof(clk_cnf_ram) / sizeof(clk_cnf_ram[0]);

    while (i < nbytes) 
    {
        u8 idx = clk_cnf_ram[i];

        debug("  Instance %d...\n\r", idx);

        if((cStatus = iic_mux_set(IicPsInstance, idx)) != 0)
        {
            error("ERROR: Could not switch to I2C bus %d\n\r", idx);
            Status |= cStatus;
            continue;
        }


        while(i < nbytes && clk_cnf_ram[i] == idx)
        {
            u8 length  = clk_cnf_ram[ i + 1 ]; 
            u8 address = clk_cnf_ram[ i + 2 ];      //Internal Clockgen register
            u8 *data = &clk_cnf_ram[ i + 3 ];

            // Make sure the calibration bit is cleared (will set it later)
            if(address <= 0x1C && address + length - 1 >= 0x1C)
            {
                data[0x1C - address] &= 0x7F;
            }

            debug("    writing %d values at address 0x%02x\n\r", length, address);

            Status = iic_write_register(IicPsInstance, IIC_SLAVE_ADDR, address, data, length);
	        if (Status != XST_SUCCESS) {
	        	return Status;
	        }

            i += length + 3; //+3 in offset for bus index and payload-length byte
        }

        if(Status == 0)
            debug("  ... OK\n\r");
        else
            error("  ... Error: %d\n\r", Status);
    }

    // TODO: Find correct requirement to waste too much time here
    //usleep(10000);

    for(int idx = 0; idx < 3; idx++)
    {
        if((cStatus = iic_mux_set(IicPsInstance, idx)) != 0)
        {
            error("ERROR: Could not switch to I2C bus %d\n\r", idx);
            Status |= cStatus;
            continue;
        }

        // Set VCO Calibration bit 0x1C
        debug("  Starting calibration on instance %d\n\r", idx);
        u8 calibration_reg;
        Status |= iic_read_register(IicPsInstance, IIC_SLAVE_ADDR, 0x1C, &calibration_reg, 1);

        if((calibration_reg & 0x80))
        {
            debug("  Clearing calibration bit\n\r");
            calibration_reg &= 0x7F; // Set bit 7 to 0
            Status |= iic_write_register(IicPsInstance, IIC_SLAVE_ADDR, 0x1C, &calibration_reg, 1);
        }

        while((!(calibration_reg & 0x80)) && Status == 0)
        {
            //usleep(1000);
            debug("  Setting calibration bit\n\r");
            calibration_reg |= 0x80; // Set bit 7 to 1
            Status |= iic_write_register(IicPsInstance, IIC_SLAVE_ADDR, 0x1C, &calibration_reg, 1);

            Status |= iic_read_register(IicPsInstance, IIC_SLAVE_ADDR, 0x1C, &calibration_reg, 1);
            debug("  Calibration register read back: 0x%02x\n\r", (u32)calibration_reg);
        }

        if(Status == 0)
            debug("  ... OK\n\r");
        else
            error("  ... Error: %d\n\r", Status);
    }

    return Status;
}